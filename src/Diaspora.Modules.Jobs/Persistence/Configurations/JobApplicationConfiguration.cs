using Diaspora.Modules.Jobs.Domain.Applications;
using Diaspora.Modules.Jobs.Domain.Identifiers;
using Diaspora.Modules.Jobs.Domain.Policies;
using Diaspora.SharedKernel.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Diaspora.Modules.Jobs.Persistence.Configurations;

/// <summary>
/// Maps the application aggregate and its three owned collections — four tables.
/// <para>
/// <b>The unique index on (candidate, posting) is the duplicate-application rule.</b> The
/// handler checks first and gives a civil error, but the index is what makes the rule true under
/// a double-tapped submit button — which on a mobile connection is not a rare event.
/// </para>
/// <para>
/// <b>The composite indexes are shaped for the two screens that matter</b>: an employer's
/// applicant list, filtered by posting and status and ordered by submission, and a candidate's
/// own tracker, filtered by member and ordered by submission. Both are read constantly and both
/// would otherwise scan an employer's entire application history.
/// </para>
/// </summary>
public sealed class JobApplicationConfiguration : IEntityTypeConfiguration<JobApplication>
{
    public void Configure(EntityTypeBuilder<JobApplication> builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.ToTable(JobPersistenceConstants.ApplicationsTable, JobsModuleMetadata.Schema);

        builder.HasKey(application => application.Id);

        builder.Property(application => application.Id)
            .HasConversion(JobValueConverters.Id<JobApplicationId>());

        builder.Property(application => application.PostingId)
            .HasConversion(JobValueConverters.Id<JobPostingId>())
            .IsRequired();

        builder.Property(application => application.EmployerId)
            .HasConversion(JobValueConverters.Id<EmployerProfileId>())
            .IsRequired();

        builder.Property(application => application.CandidateId)
            .HasConversion(JobValueConverters.Id<CandidateProfileId>())
            .IsRequired();

        builder.Property(application => application.ApplicantUserId)
            .HasConversion(JobValueConverters.Id<UserId>())
            .IsRequired();

        builder.Property(application => application.ResumeId)
            .HasConversion(JobValueConverters.Id<ResumeId>());

        builder.Property(application => application.CoverLetter)
            .HasMaxLength(JobLimits.MaxCoverLetter);

        builder.Property(application => application.Status)
            .HasConversion<string>()
            .HasMaxLength(JobPersistenceConstants.EnumLength)
            .IsRequired();

        builder.Property(application => application.StageKey)
            .HasMaxLength(JobLimits.MaxStageKey);

        builder.Property(application => application.DecisionReason)
            .HasMaxLength(JobLimits.MaxApplicationNote);

        builder.Property(application => application.Revision).IsConcurrencyToken();

        ConfigureAnswers(builder);
        ConfigureAttachments(builder);
        ConfigureHistory(builder);

        ConfigureIndexes(builder);

        builder.Ignore(application => application.DomainEvents);
        builder.Ignore(application => application.OwnerId);
        builder.Ignore(application => application.IsActive);
        builder.Ignore(application => application.CanWithdraw);
        builder.Ignore(application => application.HasBeenViewed);
        builder.Ignore(application => application.TimeToFirstResponse);
        builder.Ignore(application => application.CandidateVisibleHistory);
    }

    private static void ConfigureAnswers(EntityTypeBuilder<JobApplication> builder) =>
        builder.OwnsMany(application => application.Answers, answer =>
        {
            answer.ToTable(
                JobPersistenceConstants.ApplicationAnswersTable, JobsModuleMetadata.Schema);

            // One answer per question, enforced by the key.
            answer.WithOwner().HasForeignKey("application_id");
            answer.HasKey("application_id", nameof(ApplicationAnswer.QuestionId));

            // The identifier half of this key is supplied by the caller, and EF marks a Guid key
            // property store-generated by convention. Left alone, EF reads a set key as "this row
            // already exists" and emits an UPDATE where an INSERT was meant, which surfaces as a
            // bogus concurrency conflict rather than a missing row.
            answer.Property(value => value.QuestionId).ValueGeneratedNever();

            // The question text is a snapshot, not a reference: an employer who edits a
            // question after applications arrive must not silently rewrite what previous
            // candidates appear to have been asked.
            answer.Property(value => value.QuestionText)
                .HasMaxLength(JobLimits.MaxQuestionLength)
                .IsRequired();

            answer.Property(value => value.Answer)
                .HasMaxLength(JobLimits.MaxAnswerLength)
                .IsRequired();

            answer.Property(value => value.Order).IsRequired();
        });

    private static void ConfigureAttachments(EntityTypeBuilder<JobApplication> builder) =>
        builder.OwnsMany(application => application.Attachments, attachment =>
        {
            attachment.ToTable(
                JobPersistenceConstants.ApplicationAttachmentsTable, JobsModuleMetadata.Schema);

            attachment.HasKey(value => value.AttachmentId);
            attachment.Property(value => value.AttachmentId).ValueGeneratedNever();

            attachment.Property(value => value.Kind)
                .HasConversion<string>()
                .HasMaxLength(JobPersistenceConstants.EnumLength)
                .IsRequired();

            // A Media reference, never bytes and never a URL.
            attachment.Property(value => value.MediaId).IsRequired();

            attachment.Property(value => value.FileName).HasMaxLength(JobLimits.MaxDisplayName);
            attachment.Property(value => value.Order).IsRequired();
        });

    /// <summary>
    /// The append-only history. The largest owned collection in the module by row count, and
    /// the one that makes an application auditable rather than a status column.
    /// </summary>
    private static void ConfigureHistory(EntityTypeBuilder<JobApplication> builder) =>
        builder.OwnsMany(application => application.History, entry =>
        {
            entry.ToTable(
                JobPersistenceConstants.ApplicationHistoryTable, JobsModuleMetadata.Schema);

            entry.HasKey(value => value.EntryId);
            entry.Property(value => value.EntryId).ValueGeneratedNever();

            entry.Property(value => value.Kind)
                .HasConversion<string>()
                .HasMaxLength(JobPersistenceConstants.EnumLength)
                .IsRequired();

            entry.Property(value => value.FromStatus)
                .HasConversion<string>()
                .HasMaxLength(JobPersistenceConstants.EnumLength);

            entry.Property(value => value.ToStatus)
                .HasConversion<string>()
                .HasMaxLength(JobPersistenceConstants.EnumLength);

            entry.Property(value => value.ActorId)
                .HasConversion(JobValueConverters.Id<UserId>());

            entry.Property(value => value.Note).HasMaxLength(JobLimits.MaxApplicationNote);

            // What separates an employer's private remark from the candidate's own timeline.
            entry.Property(value => value.IsVisibleToCandidate).IsRequired();

            entry.Property(value => value.OccurredAt).IsRequired();

            entry.HasIndex(value => value.OccurredAt)
                .HasDatabaseName("ix_job_application_history_occurred");
        });

    private static void ConfigureIndexes(EntityTypeBuilder<JobApplication> builder)
    {
        // One application per candidate per posting. The handler gives a civil error; this is
        // what makes the rule true under a double-tapped submit on a poor connection.
        builder.HasIndex(application => new { application.CandidateId, application.PostingId })
            .IsUnique()
            .HasDatabaseName("ux_job_applications_candidate_posting");

        // The employer's applicant list, filtered and ordered exactly as the screen reads it.
        builder.HasIndex(application =>
                new { application.PostingId, application.Status, application.SubmittedAt })
            .HasDatabaseName("ix_job_applications_posting_status");

        // The employer-wide pipeline view.
        builder.HasIndex(application =>
                new { application.EmployerId, application.Status, application.SubmittedAt })
            .HasDatabaseName("ix_job_applications_employer_status");

        // The candidate's own tracker.
        builder.HasIndex(application =>
                new { application.ApplicantUserId, application.SubmittedAt })
            .HasDatabaseName("ix_job_applications_applicant");

        // The ghosting sweep: submitted long ago, never responded to.
        builder.HasIndex(application =>
                new { application.FirstRespondedAt, application.SubmittedAt })
            .HasDatabaseName("ix_job_applications_unanswered");

        builder.HasIndex(application => application.LastActivityAt)
            .HasDatabaseName("ix_job_applications_last_activity");
    }
}
