namespace Diaspora.SharedKernel.Contracts;

/// <summary>
/// Names the enum a <see langword="string"/> property is really drawn from, so the published
/// contract can list the values it will accept.
/// </summary>
/// <remarks>
/// <para>
/// Several request DTOs take an enum as a string on purpose. <c>CreateAdCampaignRequest.Objective</c>
/// is the clearest case: the handler parses it case-insensitively and answers with the domain's own
/// <c>ObjectiveUnknown</c>, which tells a caller what is wrong far better than the model binder's
/// 400 on an unbindable enum. Binding to <c>AdCampaignObjective?</c> would trade that message for a
/// worse one.
/// </para>
/// <para>
/// <b>The cost was that the contract said nothing.</b> The document described the property as
/// <c>{"type": ["null", "string"]}</c>, so the four legal values existed only in C#. A client
/// shipped six objectives, four of which the server refuses outright, and every contract check
/// passed — because the contract made no claim to check against.
/// </para>
/// <para>
/// That was worth getting right for its own sake, and worth recording how it was misread: the
/// document was assumed stale. It is not. <c>contracts/Diaspora.Api.json</c> is regenerated by
/// every build of <c>Diaspora.Api</c> and carried all seventeen advertising routes the whole time.
/// It could not express the values, which is a different fault with a different fix.
/// </para>
/// <para>
/// This attribute closes the gap without touching how anything binds: the property stays a string,
/// the handler keeps its own error, and the document gains the <c>enum</c> list a consumer can read.
/// It lives here rather than beside its transformer because a module cannot reference the API
/// project, and it deliberately carries no OpenAPI dependency of its own — it names a type and
/// nothing more.
/// </para>
/// </remarks>
[AttributeUsage(AttributeTargets.Property, AllowMultiple = false)]
public sealed class OpenApiEnumValuesAttribute : Attribute
{
    public OpenApiEnumValuesAttribute(Type enumType)
    {
        ArgumentNullException.ThrowIfNull(enumType);

        if (!enumType.IsEnum)
        {
            throw new ArgumentException($"{enumType.Name} is not an enum.", nameof(enumType));
        }

        EnumType = enumType;
    }

    public Type EnumType { get; }
}
