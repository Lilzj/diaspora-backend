using Diaspora.Modules.Guides.Domain.Directories;
using Diaspora.Modules.Guides.Domain.Identifiers;
using Diaspora.Modules.Guides.Domain.Policies;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Diaspora.Modules.Guides.Persistence.Configurations;

/// <summary>
/// Maps a country's knowledge directory and the three collections it owns.
/// <para>
/// <b>The featured shelf keys on a caller-supplied surrogate, and that is not laziness.</b> Its
/// natural identity is (guide, category) and the category half is nullable — a guide can be
/// featured on the country's own shelf rather than within a subject — and a nullable column inside a
/// composite primary key behaves differently on every provider. The aggregate enforces the pair's
/// uniqueness, which is where that rule actually lives, and the surrogate is declared
/// <c>ValueGeneratedNever</c>: EF marks a Guid key store-generated by convention, reads a
/// caller-set value as "this row already exists", emits an UPDATE where an INSERT was meant, and
/// surfaces it as a bogus concurrency conflict.
/// </para>
/// <para>
/// <b>The unique index is on the country code, not the primary key.</b> The surrogate exists so the
/// platform's audit, soft-delete and outbox conventions apply unchanged; the country is what
/// actually has to be unique, and it is where every read goes.
/// </para>
/// </summary>
public sealed class CountryKnowledgeDirectoryConfiguration
    : IEntityTypeConfiguration<CountryKnowledgeDirectory>
{
    public void Configure(EntityTypeBuilder<CountryKnowledgeDirectory> builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.ToTable(
            KnowledgePersistenceConstants.CountryDirectoriesTable, GuidesModuleMetadata.Schema);

        builder.HasKey(directory => directory.Id);

        builder.Property(directory => directory.Id)
            .HasConversion(GuideValueConverters.Id<CountryKnowledgeDirectoryId>());

        builder.Property(directory => directory.CountryCode)
            .HasMaxLength(KnowledgePersistenceConstants.CountryCodeLength)
            .IsRequired();

        builder.Property(directory => directory.DisplayName)
            .HasMaxLength(KnowledgeLimits.MaxDirectoryName)
            .IsRequired();

        builder.Property(directory => directory.Summary)
            .HasMaxLength(KnowledgeLimits.MaxDirectorySummary);

        builder.Property(directory => directory.PrimaryLanguage)
            .HasMaxLength(KnowledgeLimits.MaxLocale);

        // A delimited column rather than a fourth owned table: a list of at most twenty two-letter
        // codes that nothing ever filters on. The aggregate owns the delimiter.
        builder.Property(directory => directory.LanguagesCsv)
            .HasMaxLength(KnowledgeLimits.MaxLocale * KnowledgeLimits.MaxDirectoryLanguages);

        builder.Property(directory => directory.Revision).IsConcurrencyToken();

        builder.HasIndex(directory => directory.CountryCode)
            .IsUnique()
            .HasDatabaseName("ux_knowledge_country_directories_country");

        // The country picker: every published directory, ordered by name.
        builder.HasIndex(directory => directory.IsPublished)
            .HasDatabaseName("ix_knowledge_country_directories_published");

        ConfigureEntries(builder);
        ConfigureFeaturedGuides(builder);
        ConfigureLocalizations(builder);

        builder.Ignore(directory => directory.DomainEvents);
        builder.Ignore(directory => directory.Languages);
        builder.Ignore(directory => directory.VisibleEntries);
    }

    private static void ConfigureEntries(EntityTypeBuilder<CountryKnowledgeDirectory> builder) =>
        builder.OwnsMany(directory => directory.Entries, entry =>
        {
            entry.ToTable(
                KnowledgePersistenceConstants.CountryDirectoryEntriesTable,
                GuidesModuleMetadata.Schema);

            entry.Property(value => value.KnowledgeCategoryKey)
                .HasMaxLength(KnowledgeLimits.MaxCategoryKey)
                .IsRequired();

            entry.Property(value => value.LabelOverride)
                .HasMaxLength(KnowledgeLimits.MaxCategoryName);

            entry.WithOwner().HasForeignKey("CountryKnowledgeDirectoryId");

            // A category appears on a directory at most once — the aggregate rejects a duplicate
            // outright — so the pair is the identity and the database enforces it.
            entry.HasKey(
                "CountryKnowledgeDirectoryId", nameof(CountryDirectoryEntry.KnowledgeCategoryKey));

            // "Which countries list this row" — the guard behind archiving a catalogue entry.
            entry.HasIndex(value => value.KnowledgeCategoryKey)
                .HasDatabaseName("ix_knowledge_directory_entries_category");
        });

    private static void ConfigureFeaturedGuides(
        EntityTypeBuilder<CountryKnowledgeDirectory> builder) =>
        builder.OwnsMany(directory => directory.FeaturedGuides, featured =>
        {
            featured.ToTable(
                KnowledgePersistenceConstants.CountryFeaturedGuidesTable,
                GuidesModuleMetadata.Schema);

            featured.HasKey(value => value.FeatureId);

            // Load-bearing, not tidiness. See the class summary.
            featured.Property(value => value.FeatureId).ValueGeneratedNever();

            featured.Property(value => value.KnowledgeCategoryKey)
                .HasMaxLength(KnowledgeLimits.MaxCategoryKey);

            featured.Property(value => value.Note)
                .HasMaxLength(KnowledgeLimits.MaxCuratorNote);

            featured.WithOwner().HasForeignKey("CountryKnowledgeDirectoryId");

            // "Which countries feature this guide" — asked when a guide is unpublished, to find
            // the shelves that will need a curator's attention.
            featured.HasIndex(value => value.GuideId)
                .HasDatabaseName("ix_knowledge_featured_guides_guide");
        });

    private static void ConfigureLocalizations(
        EntityTypeBuilder<CountryKnowledgeDirectory> builder) =>
        builder.OwnsMany(directory => directory.Localizations, localization =>
        {
            localization.ToTable(
                KnowledgePersistenceConstants.CountryDirectoryLocalizationsTable,
                GuidesModuleMetadata.Schema);

            localization.Property(value => value.Locale)
                .HasMaxLength(KnowledgeLimits.MaxLocale)
                .IsRequired();

            localization.Property(value => value.DisplayName)
                .HasMaxLength(KnowledgeLimits.MaxDirectoryName)
                .IsRequired();

            localization.Property(value => value.Summary)
                .HasMaxLength(KnowledgeLimits.MaxDirectorySummary);

            localization.WithOwner().HasForeignKey("CountryKnowledgeDirectoryId");

            localization.HasKey(
                "CountryKnowledgeDirectoryId", nameof(CountryDirectoryLocalization.Locale));
        });
}
