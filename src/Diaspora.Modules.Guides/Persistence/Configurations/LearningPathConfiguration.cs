using Diaspora.Modules.Guides.Domain.Identifiers;
using Diaspora.Modules.Guides.Domain.LearningPaths;
using Diaspora.Modules.Guides.Domain.Policies;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Diaspora.Modules.Guides.Persistence.Configurations;

/// <summary>
/// Maps a curated learning path and its steps.
/// <para>
/// <b>The unique index spans country and key, not the key alone.</b> That is what lets
/// <c>arriving</c> be the natural key for the arrival path of every country — a global unique key
/// would force curators to invent <c>arriving-mu</c> and <c>arriving-ca</c>, which puts the country
/// in the identifier twice and in the URL twice.
/// </para>
/// <para>
/// Steps key on their caller-supplied identifier, declared <c>ValueGeneratedNever</c> for the reason
/// the platform has now recorded in three phases: EF marks a Guid key store-generated by convention,
/// reads a caller-set value as an existing row, and emits an UPDATE where an INSERT was meant. The
/// identifier is caller-supplied because a client tracking "you are on step 3" tracks it against
/// this, and an editor inserting a step above must not advance every reader.
/// </para>
/// <para>
/// Not soft-deletable, deliberately. Archived is the terminal status and the rows stay: a path that
/// was correct until a country changed its visa rules records what the advice used to be.
/// </para>
/// </summary>
public sealed class LearningPathConfiguration : IEntityTypeConfiguration<LearningPath>
{
    public void Configure(EntityTypeBuilder<LearningPath> builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.ToTable(
            KnowledgePersistenceConstants.LearningPathsTable, GuidesModuleMetadata.Schema);

        builder.HasKey(path => path.Id);

        builder.Property(path => path.Id)
            .HasConversion(GuideValueConverters.Id<LearningPathId>());

        builder.Property(path => path.Key)
            .HasMaxLength(KnowledgeLimits.MaxPathKey)
            .IsRequired();

        builder.Property(path => path.CountryCode)
            .HasMaxLength(KnowledgePersistenceConstants.CountryCodeLength)
            .IsRequired();

        builder.Property(path => path.Title)
            .HasMaxLength(KnowledgeLimits.MaxPathTitle)
            .IsRequired();

        builder.Property(path => path.Description)
            .HasMaxLength(KnowledgeLimits.MaxPathDescription);

        builder.Property(path => path.Language)
            .HasMaxLength(KnowledgeLimits.MaxLocale);

        builder.Property(path => path.Status)
            .HasConversion<string>()
            .HasMaxLength(KnowledgePersistenceConstants.EnumLength)
            .IsRequired();

        builder.Property(path => path.Revision).IsConcurrencyToken();

        builder.HasIndex(path => new { path.CountryCode, path.Key })
            .IsUnique()
            .HasDatabaseName("ux_knowledge_learning_paths_country_key");

        // Every listing is "the published paths for this country".
        builder.HasIndex(path => new { path.CountryCode, path.Status })
            .HasDatabaseName("ix_knowledge_learning_paths_country_status");

        ConfigureSteps(builder);

        builder.Ignore(path => path.DomainEvents);
        builder.Ignore(path => path.RequiredStepCount);
        builder.Ignore(path => path.IsPublishable);
    }

    private static void ConfigureSteps(EntityTypeBuilder<LearningPath> builder) =>
        builder.OwnsMany(path => path.Steps, step =>
        {
            step.ToTable(
                KnowledgePersistenceConstants.LearningPathStepsTable, GuidesModuleMetadata.Schema);

            step.HasKey(value => value.StepId);
            step.Property(value => value.StepId).ValueGeneratedNever();

            step.Property(value => value.Title)
                .HasMaxLength(KnowledgeLimits.MaxStepTitle)
                .IsRequired();

            step.Property(value => value.Description)
                .HasMaxLength(KnowledgeLimits.MaxStepDescription);

            step.Property(value => value.KnowledgeCategoryKey)
                .HasMaxLength(KnowledgeLimits.MaxCategoryKey);

            step.WithOwner().HasForeignKey("LearningPathId");

            // "Which paths point at this guide" — what a curator needs when a guide is unpublished.
            step.HasIndex(value => value.GuideId)
                .HasDatabaseName("ix_knowledge_learning_path_steps_guide");
        });
}
