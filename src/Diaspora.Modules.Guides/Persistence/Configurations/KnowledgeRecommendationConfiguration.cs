using Diaspora.Modules.Guides.Domain.Identifiers;
using Diaspora.Modules.Guides.Domain.Policies;
using Diaspora.Modules.Guides.Domain.Recommendations;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

// The kernel's legacy identifier bag (Diaspora.SharedKernel.Identity) also declares a GuideId.
using GuideId = Diaspora.Modules.Guides.Domain.Identifiers.GuideId;

namespace Diaspora.Modules.Guides.Persistence.Configurations;

/// <summary>
/// Maps curated next-read sets.
/// <para>
/// <b>The source guide is uniquely indexed rather than being the key.</b> One recommendation set per
/// guide is the rule, and a unique index on a value-converted identifier enforces it while leaving
/// the primary key an ordinary surrogate the audit interceptor and the outbox both already
/// understand. Making the guide identifier the key would have been tidier and would have opted this
/// one aggregate out of three platform conventions.
/// </para>
/// <para>
/// The read collection keys on (recommendation, guide), which is the domain identity: the aggregate
/// collapses a repeated guide, so a duplicate cannot reach the table.
/// </para>
/// </summary>
public sealed class KnowledgeRecommendationConfiguration
    : IEntityTypeConfiguration<KnowledgeRecommendation>
{
    public void Configure(EntityTypeBuilder<KnowledgeRecommendation> builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        builder.ToTable(
            KnowledgePersistenceConstants.RecommendationsTable, GuidesModuleMetadata.Schema);

        builder.HasKey(recommendation => recommendation.Id);

        builder.Property(recommendation => recommendation.Id)
            .HasConversion(GuideValueConverters.Id<KnowledgeRecommendationId>());

        builder.Property(recommendation => recommendation.SourceGuideId)
            .HasConversion(GuideValueConverters.Id<GuideId>())
            .IsRequired();

        builder.Property(recommendation => recommendation.Revision).IsConcurrencyToken();

        builder.HasIndex(recommendation => recommendation.SourceGuideId)
            .IsUnique()
            .HasDatabaseName("ux_knowledge_recommendations_source");

        ConfigureReads(builder);

        builder.Ignore(recommendation => recommendation.DomainEvents);
    }

    private static void ConfigureReads(EntityTypeBuilder<KnowledgeRecommendation> builder) =>
        builder.OwnsMany(recommendation => recommendation.Reads, read =>
        {
            read.ToTable(
                KnowledgePersistenceConstants.RecommendedReadsTable, GuidesModuleMetadata.Schema);

            read.Property(value => value.Reason)
                .HasMaxLength(KnowledgeLimits.MaxCuratorNote);

            read.WithOwner().HasForeignKey("KnowledgeRecommendationId");

            read.HasKey("KnowledgeRecommendationId", nameof(RecommendedRead.GuideId));

            // The identifier half of this key is supplied by the caller, and EF marks a Guid key
            // property store-generated by convention. Left alone, EF reads a set key as an existing
            // row and emits an UPDATE where an INSERT was meant.
            read.Property(value => value.GuideId).ValueGeneratedNever();

            // "Which guides recommend this one" — the reverse lookup a curator uses to find the
            // sets that need attention when a guide is withdrawn.
            read.HasIndex(value => value.GuideId)
                .HasDatabaseName("ix_knowledge_recommended_reads_guide");
        });
}
