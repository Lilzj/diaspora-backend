using Diaspora.Modules.Housing.Domain.Policies;

namespace Diaspora.Modules.Housing.Domain.Listings;

/// <summary>
/// One thing the landlord asks of whoever lives there.
/// <para>
/// <b>Free text and ordered, rather than a fixed vocabulary.</b> Smoking, pets and noise already
/// have typed fields on the listing because they are filtered on; a house rule is everything else
/// - "shoes off indoors", "no visitors after 11", "the gate is locked at midnight" - and those are
/// not enumerable across the countries this platform spans. Trying would produce a list that is
/// wrong everywhere and a landlord writing the real rule in the description anyway.
/// </para>
/// </summary>
public sealed class HouseRule
{
    private HouseRule(Guid ruleId, string text, int order)
    {
        RuleId = ruleId;
        Text = text;
        Order = order;
    }

    private HouseRule() { }

    /// <summary>
    /// The row's own key, supplied by the caller rather than generated by the database - EF emits
    /// an UPDATE instead of an INSERT for a caller-keyed owned collection unless the configuration
    /// says ValueGeneratedNever, and it surfaces as a bogus concurrency conflict.
    /// </summary>
    public Guid RuleId { get; private set; }

    public string Text { get; private set; } = string.Empty;

    public int Order { get; private set; }

    public static HouseRule Create(Guid ruleId, string? text, int order)
    {
        var trimmed = text?.Trim() ?? string.Empty;

        if (trimmed.Length > HousingLimits.MaxHouseRuleLength)
        {
            trimmed = trimmed[..HousingLimits.MaxHouseRuleLength];
        }

        return new HouseRule(ruleId, trimmed, order);
    }
}
