using Diaspora.Modules.Housing.Domain.Enums;
using Diaspora.Modules.Housing.Domain.Policies;
using Diaspora.SharedKernel.Identity;

namespace Diaspora.Modules.Housing.Domain.Viewings;

/// <summary>
/// One step in a viewing's life, recorded as it happened.
/// <para>
/// <b>Append-only, and it is the record a dispute is settled from.</b> "You never confirmed a
/// time" and "I cancelled two days before" are both claims two people make in good faith about the
/// same viewing, and the only thing that can settle it is a trail neither of them can edit.
/// </para>
/// <para>
/// The key is supplied by the caller rather than generated by the database - EF emits an UPDATE
/// instead of an INSERT for a caller-keyed owned collection unless the configuration says
/// ValueGeneratedNever, and the symptom is a bogus concurrency conflict rather than a missing row.
/// </para>
/// </summary>
public sealed class ViewingHistoryEntry
{
    private ViewingHistoryEntry(
        Guid entryId,
        HousingViewingStatus status,
        UserId? actorId,
        string? reason,
        DateTimeOffset occurredAt)
    {
        EntryId = entryId;
        Status = status;
        ActorId = actorId;
        Reason = reason;
        OccurredAt = occurredAt;
    }

    private ViewingHistoryEntry() { }

    public Guid EntryId { get; private set; }

    public HousingViewingStatus Status { get; private set; }

    /// <summary>Who did it. Null when the expiry sweep did.</summary>
    public UserId? ActorId { get; private set; }

    public string? Reason { get; private set; }

    public DateTimeOffset OccurredAt { get; private set; }

    public static ViewingHistoryEntry Create(
        Guid entryId,
        HousingViewingStatus status,
        UserId? actorId,
        string? reason,
        DateTimeOffset occurredAt)
    {
        var trimmed = string.IsNullOrWhiteSpace(reason) ? null : reason.Trim();

        if (trimmed is { Length: > HousingLimits.MaxViewingNote })
        {
            trimmed = trimmed[..HousingLimits.MaxViewingNote];
        }

        return new ViewingHistoryEntry(entryId, status, actorId, trimmed, occurredAt);
    }
}
