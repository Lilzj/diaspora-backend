using Diaspora.Modules.Community.Domain.Posts;
using Diaspora.Modules.Community.Domain.ValueObjects;

namespace Diaspora.Modules.Community.Extensibility.Feeds;

/// <summary>
/// One entry in a feed, with whatever the ranker needs to place it.
/// <para>
/// Carries the post when the feed is over B6's own content, and a bare reference when it is not
/// — a mixed feed of posts and guides is a legitimate thing for a provider to build, and forcing
/// one to fabricate a post to say so would be worse than either.
/// </para>
/// <para>
/// <see cref="SortKey"/> is what the cursor encodes. A provider that leaves it at zero gets
/// chronological cursors; one that sets a score gets score cursors, and the same cursor type
/// serves both.
/// </para>
/// </summary>
public sealed record FeedItem
{
    public required ContentReference Reference { get; init; }

    /// <summary>Present when the item is one of Community's own posts.</summary>
    public CommunityPost? Post { get; init; }

    /// <summary>The ranking score, or the timestamp for a chronological feed.</summary>
    public double SortKey { get; init; }

    public DateTimeOffset? PublishedAt { get; init; }

    /// <summary>Set by the nearby feed. Always a distance Location computed, never one B6 did.</summary>
    public double? DistanceKm { get; init; }

    /// <summary>
    /// Why this item is here, for a client that wants to say so. Never required, and never
    /// generated by B6 — a ranking strategy that can explain itself sets it.
    /// </summary>
    public string? Reason { get; init; }

    public static FeedItem ForPost(CommunityPost post, double sortKey, double? distanceKm = null)
    {
        ArgumentNullException.ThrowIfNull(post);

        return new FeedItem
        {
            Reference = post.Reference,
            Post = post,
            SortKey = sortKey,
            PublishedAt = post.PublishedAt,
            DistanceKm = distanceKm
        };
    }
}
