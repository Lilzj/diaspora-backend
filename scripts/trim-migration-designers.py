#!/usr/bin/env python3
"""Cut old EF Core migration designers down to their attributes.

Every `dotnet ef migrations add` writes a designer holding a whole copy of the model, and enough of
them stop Diaspora.Persistence compiling on the Fly builder. Why this is safe, and what keeps it safe:
tests/Diaspora.ArchitectureTests/MigrationDesignerArchitectureTests.cs.

Safe to run twice. The newest --keep designers stay as scaffolded, and so do the two that a migration
needs if EF writes its SQL by reading the model. If a designer is not one the script recognises, it stops.

    python scripts/trim-migration-designers.py [--keep 5]

Compare `dotnet ef migrations script --idempotent` before and after: the SQL must not change.
"""
import argparse
import pathlib
import re
import sys

MIGRATIONS = pathlib.Path(__file__).resolve().parent.parent / "src" / "Diaspora.Persistence" / "Migrations"

# EF reads a model to write the SQL for these: the migration's own for Up, the previous one's for Down.
READS_THE_MODEL = ("AlterColumn<", "InsertData(", "UpdateData(", "DeleteData(")

DECLARATION = re.compile(
    r'namespace (?P<namespace>[\w.]+)\s*\{\s*'
    r'(?:// [^\n]*\n\s*)?'
    r'\[DbContext\(typeof\((?P<context>\w+)\)\)\]\s*'
    r'\[Migration\("(?P<id>[^"]+)"\)\]\s*'
    r'partial class (?P<name>\w+)')

TRIMMED = """﻿// <auto-generated />
using Diaspora.Persistence;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

#nullable disable

namespace {namespace}
{{
    // Model trimmed by scripts/trim-migration-designers.py.
    [DbContext(typeof({context}))]
    [Migration("{id}")]
    partial class {name}
    {{
    }}
}}
"""


def reads_the_model(designer: pathlib.Path) -> bool:
    migration = designer.with_name(designer.name.replace(".Designer.cs", ".cs"))
    source = migration.read_text(encoding="utf-8-sig")

    return any(operation in source for operation in READS_THE_MODEL)


def main() -> int:
    parser = argparse.ArgumentParser(description="Trim old EF Core migration designers.")
    parser.add_argument("--keep", type=int, default=5, help="newest designers to leave as scaffolded")
    keep = parser.parse_args().keep

    if keep < 2:
        parser.error("--keep must be at least 2: removing a migration reads the previous one's model")

    designers = sorted(MIGRATIONS.glob("*.Designer.cs"), key=lambda path: path.name)
    stays = set(designers[-keep:])

    for index, designer in enumerate(designers):
        if reads_the_model(designer):
            stays.update(designers[max(index - 1, 0):index + 1])

    trimmed = 0

    for designer in designers:
        text = designer.read_text(encoding="utf-8-sig")

        if designer in stays or "BuildTargetModel" not in text:
            continue

        match = DECLARATION.search(text)

        if match is None:
            print(f"Not a designer this script knows how to read: {designer.name}", file=sys.stderr)
            return 1

        designer.write_text(TRIMMED.format(**match.groupdict()), encoding="utf-8", newline="\n")
        trimmed += 1

    print(f"Trimmed {trimmed} of {len(designers)} designers; {len(stays)} keep their model.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
